// Barcode Lookup index
export function lookupFoodByBarcode(barcodeStr: string): FoodDatabaseEntry | null {
  const cleanCode = barcodeStr.trim();
  const match = globalFoodDatabase.find(
    (f) => f.barcode === cleanCode || f.id.toLowerCase() === cleanCode.toLowerCase()
  );
  return match || null;
}

// Global Text / Tag Search across 100+ foods
export function searchGlobalFoodDatabase(query: string, category?: string): FoodDatabaseEntry[] {
  const q = query.trim().toLowerCase();
  return globalFoodDatabase.filter((f) => {
    if (category && category !== 'All Categories' && f.category !== category) {
      return false;
    }
    if (!q) return true;
    const matchName = f.name.toLowerCase().includes(q);
    const matchTag = f.tags.some((t) => t.toLowerCase().includes(q));
    const matchBarcode = f.barcode && f.barcode.includes(q);
    return matchName || matchTag || matchBarcode;
  });
}
